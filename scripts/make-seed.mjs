// Generates supabase/seed.sql from the built-in demo templates:  node scripts/make-seed.mjs
import { build } from "esbuild";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const out = join(mkdtempSync(join(tmpdir(), "seed-")), "demo.mjs");
await build({ entryPoints: ["src/lib/demoData.ts"], bundle: true, format: "esm", outfile: out, logLevel: "silent" });
const { demoCategories, demoTemplates } = await import(out);
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
let sql = "-- Starter templates. Run after schema.sql. Generated by scripts/make-seed.mjs\n";
for (const c of demoCategories) sql += `insert into public.categories (id, name) values (${q(c.id)}, ${q(c.name)}) on conflict (id) do nothing;\n`;
for (const t of demoTemplates) sql += `insert into public.templates (id, category_id, name, html_code) values (${q(t.id)}, ${q(t.category_id)}, ${q(t.name)}, ${q(t.html_code)}) on conflict (id) do nothing;\n`;
writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
